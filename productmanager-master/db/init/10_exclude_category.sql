-- Исключённые категории продуктов (мясо, рыба и т.п.)
CREATE TABLE IF NOT EXISTS exclude_category (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT NOT NULL,
    category VARCHAR(32) NOT NULL,
    CONSTRAINT fk_exclude_category_user
        FOREIGN KEY (user_id) REFERENCES user_profile (id) ON DELETE CASCADE,
    CONSTRAINT uk_exclude_category_user_category UNIQUE (user_id, category),
    CONSTRAINT chk_exclude_category_value CHECK (category IN (
        'MEAT', 'FISH', 'SEAFOOD', 'DAIRY', 'EGGS', 'GRAINS', 'PASTA', 'BREAD',
        'VEGETABLES', 'FRUITS', 'BERRIES', 'NUTS', 'LEGUMES', 'OIL', 'SAUCES',
        'SWEETS', 'BEVERAGES', 'OTHER'))
);

CREATE INDEX IF NOT EXISTS idx_exclude_category_user ON exclude_category (user_id);
