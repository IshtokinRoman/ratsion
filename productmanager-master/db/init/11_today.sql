-- Дата старта плана, активный план и лог «съел / пропустил»
-- active: сначала nullable, потом NOT NULL — иначе Hibernate/PG падают на существующих строках
ALTER TABLE meal_plan ADD COLUMN IF NOT EXISTS start_date DATE;
ALTER TABLE meal_plan ADD COLUMN IF NOT EXISTS active BOOLEAN;
UPDATE meal_plan SET active = FALSE WHERE active IS NULL;
UPDATE meal_plan SET start_date = CURRENT_DATE WHERE start_date IS NULL;
ALTER TABLE meal_plan ALTER COLUMN active SET DEFAULT FALSE;
ALTER TABLE meal_plan ALTER COLUMN active SET NOT NULL;

CREATE TABLE IF NOT EXISTS meal_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id BIGINT NOT NULL,
    user_id      BIGINT NOT NULL,
    day_number   INTEGER NOT NULL,
    meal_type    VARCHAR(32) NOT NULL,
    status       VARCHAR(16) NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_meal_log_plan
        FOREIGN KEY (meal_plan_id) REFERENCES meal_plan (id) ON DELETE CASCADE,
    CONSTRAINT fk_meal_log_user
        FOREIGN KEY (user_id) REFERENCES user_profile (id) ON DELETE CASCADE,
    CONSTRAINT uk_meal_log_plan_day_type UNIQUE (meal_plan_id, day_number, meal_type),
    CONSTRAINT chk_meal_log_day CHECK (day_number >= 1),
    CONSTRAINT chk_meal_log_type CHECK (meal_type IN (
        'BREAKFAST', 'LUNCH', 'DINNER', 'SNACK', 'SECOND_SNACK')),
    CONSTRAINT chk_meal_log_status CHECK (status IN ('EATEN', 'SKIPPED'))
);

CREATE INDEX IF NOT EXISTS idx_meal_log_plan ON meal_log (meal_plan_id);
CREATE INDEX IF NOT EXISTS idx_meal_log_user ON meal_log (user_id);
CREATE INDEX IF NOT EXISTS idx_meal_plan_owner_active ON meal_plan (owner_id, active);