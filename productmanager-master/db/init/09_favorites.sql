-- Избранные блюда пользователя
CREATE TABLE IF NOT EXISTS favorite_dish (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    dish_id BIGINT NOT NULL,
    CONSTRAINT fk_favorite_dish_user
        FOREIGN KEY (user_id) REFERENCES user_profile (id) ON DELETE CASCADE,
    CONSTRAINT fk_favorite_dish_dish
        FOREIGN KEY (dish_id) REFERENCES dish (id) ON DELETE CASCADE,
    CONSTRAINT uk_favorite_dish_user_dish UNIQUE (user_id, dish_id)
);

CREATE INDEX IF NOT EXISTS idx_favorite_dish_user ON favorite_dish (user_id);
CREATE INDEX IF NOT EXISTS idx_favorite_dish_dish ON favorite_dish (dish_id);
